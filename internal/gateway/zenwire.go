package gateway

// zen's free tier is gated on the client's wire fingerprint, not just the
// request shape. Bisected against live zen on 2026-11-25, a request that
// passes every body/header rule (stream:true, a tool named "read", a
// structurally valid x-opencode-session) still answers
//
//	429 {"type":"error","error":{"type":"FreeUsageLimitError",…}}
//
// unless it arrives exactly the way the opencode CLI (the bun runtime)
// sends it. What the airlock inspects:
//
//   - the TLS ClientHello: bun's hello passes; curl/OpenSSL, Go's
//     crypto/tls and even a Chrome-shaped uTLS preset are all rejected
//   - the HTTP/1.1 head: bun's header order and casing. Go's http.Transport
//     canonicalizes x-opencode-session to X-Opencode-Session and sorts the
//     head — same TLS hello, still rejected. bun (ALPN "http/1.1" only)
//     never speaks h2 to zen.
//
// Both were verified by replaying the captured ClientHello with uTLS and a
// hand-written request head: 200s where the transport-level client gets
// 429s on every attempt (and, conversely, a body without stream/tools on
// the right wire gets 429s — the body rules from zenfp.go still apply).
//
// zenDo is therefore a small purpose-built HTTP/1.1 client: it opens a uTLS
// connection replaying opencode 1.19.6's ClientHello (zenBunHello, captured
// from opencode 1.19.6 / bun 1.4.4 with `openssl s_server -msg`, see
// the recapture recipe at the bottom of this comment) and writes the request head in bun's
// exact shape:
//
//	Authorization, Content-Type, User-Agent, x-opencode-client,
//	x-opencode-project, x-opencode-request, x-opencode-session,
//	x-opencode-session-id, Connection, Accept, Host, Accept-Encoding,
//	Content-Length
//
// One connection per request: no pooling, closed when the body closes or
// the client context is cancelled. The TLS handshake and key shares are
// regenerated by uTLS per connection; only the hello's shape is replayed.
//
// Recapturing (when zen tightens again and the hello stops matching):
// run an openssl s_server with a self-signed cert, point opencode's zen
// provider at it (provider.opencode.options.baseURL in opencode.json,
// NODE_TLS_REJECT_UNAUTHORIZED=0), `opencode run -m opencode/<model>`,
// take the first ClientHello from the -msg log, prepend the record header
// 16 03 01 <len16> and base64 it into zenBunHello.

