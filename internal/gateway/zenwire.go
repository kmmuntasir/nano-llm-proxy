// zenDialTimeout and zenHandshakeTimeout mirror initHTTPClient's transport.
const (
	zenDialTimeout      = 10 * time.Second
	zenHandshakeTimeout = 10 * time.Second
)

// zenDo POSTs body to rawURL with the zen key, over the opencode wire.
// The returned Response has a fully decoded body (chunked framing removed,
// gzip/zlib inflated); callers must Close it.
func (g *gateway) zenDo(ctx context.Context, rawURL, key string, body []byte) (*http.Response, error) {
	u, err := url.Parse(rawURL)
	if err != nil {
		return nil, err
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return nil, fmt.Errorf("zen: unsupported scheme %q", u.Scheme)
	}
	addr := u.Host
	if !strings.Contains(addr, ":") {
		if u.Scheme == "https" {
			addr += ":443"
		} else {
			addr += ":80"
		}
	}
	host := u.Hostname()

	dialCtx, dialCancel := context.WithTimeout(ctx, zenDialTimeout)
	defer dialCancel()
	var d net.Dialer
	tcp, err := d.DialContext(dialCtx, "tcp", addr)
	if err != nil {
		return nil, err
	}
	conn := net.Conn(tcp)
	if u.Scheme == "https" {
		hc, hcancel := context.WithTimeout(ctx, zenHandshakeTimeout)
		defer hcancel()
		conn, err = zenTLSHandshake(hc, tcp, host)
		if err != nil {
			tcp.Close()
			return nil, err
		}
	}

	ua := g.rs().Zen.UserAgent
	if ua == "" {
		ua = settings.DefaultZenUserAgent
	}
	sid := newZenSessionID()

	var head strings.Builder
	head.WriteString("POST " + u.RequestURI() + " HTTP/1.1\r\n")
	head.WriteString("Authorization: Bearer " + key + "\r\n")
	head.WriteString("Content-Type: application/json\r\n")
	head.WriteString("User-Agent: " + ua + "\r\n")
	head.WriteString("x-opencode-client: cli\r\n")
	head.WriteString("x-opencode-project: global\r\n")
	head.WriteString("x-opencode-request: " + newZenRequestID() + "\r\n")
	head.WriteString("x-opencode-session: " + sid + "\r\n")
	head.WriteString("x-opencode-session-id: " + sid + "\r\n")
	head.WriteString("Connection: keep-alive\r\n")
	head.WriteString("Accept: */*\r\n")
	head.WriteString("Host: " + u.Host + "\r\n")
	// bun's exact list — br/zstd are accepted upstream but never seen on
	// zen's SSE replies; gzip and deflate (zlib) are decoded in zenBody.
	head.WriteString("Accept-Encoding: gzip, deflate, br, zstd\r\n")
	head.WriteString("Content-Length: " + strconv.Itoa(len(body)) + "\r\n\r\n")

	if _, err := conn.Write(append([]byte(head.String()), body...)); err != nil {
		conn.Close()
		return nil, err
	}

	// read the response head with a bounded deadline (ResponseHeaderTimeout)
	_ = conn.SetReadDeadline(time.Now().Add(120 * time.Second))
	br := bufio.NewReader(conn)
	statusLine, err := br.ReadString('\n')
	if err != nil {
		conn.Close()
		return nil, err
	}
	code := statusLine
	if i := strings.IndexByte(statusLine, ' '); i >= 0 {
		code = code[i+1:]
	}
	statusCode, err := strconv.Atoi(strings.TrimSpace(strings.Fields(code)[0]))
	if err != nil {
		conn.Close()
		return nil, fmt.Errorf("zen: malformed status line %q", strings.TrimSpace(statusLine))
	}
	hdr := readRawHeaders(br)
	// body reads have no deadline: SSE streams run for minutes
	_ = conn.SetReadDeadline(time.Time{})

	return &http.Response{
		Status:        strings.TrimSpace(statusLine),
		StatusCode:    statusCode,
		Proto:         "HTTP/1.1",
		ProtoMajor:    1,
		ProtoMinor:    1,
		Header:        hdr,
		Body:          newZenBody(br, conn, hdr, ctx),
		ContentLength: -1,
	}, nil
}

// readRawHeaders reads MIME-style headers into an http.Header.
func readRawHeaders(br *bufio.Reader) http.Header {
	hdr := http.Header{}
	for {
		line, err := br.ReadString('\n')
		if err != nil || line == "\r\n" || line == "\n" {
			return hdr
		}
		if i := strings.IndexByte(line, ':'); i > 0 {
			hdr.Add(strings.TrimSpace(line[:i]), strings.TrimSpace(line[i+1:]))
		}
	}
}

// zenTLSHandshake wraps tcp in a uTLS connection replaying the bun hello.
func zenTLSHandshake(ctx context.Context, tcp net.Conn, host string) (net.Conn, error) {
	raw, err := base64.StdEncoding.DecodeString(zenBunHello)
	if err != nil {
		return nil, err
	}
	spec, err := (&utls.Fingerprinter{AllowBluntMimicry: true}).FingerprintClientHello(raw)
	if err != nil {
		return nil, err
	}
	for _, ext := range spec.Extensions {
		if sni, ok := ext.(*utls.SNIExtension); ok {
			sni.ServerName = host
		}
	}
	uconn := utls.UClient(tcp, &utls.Config{ServerName: host}, utls.HelloCustom)
	if err := uconn.ApplyPreset(spec); err != nil {
		return nil, err
	}
	if err := uconn.HandshakeContext(ctx); err != nil {
		return nil, err
	}
	return uconn, nil
}

// zenBody decodes the response body (chunked framing, gzip/zlib) and owns
// the connection: Close tears it down, as does a cancelled request context.
type zenBody struct {
	src    io.Reader // framing/compression-decoded body
	conn   net.Conn
	cancel chan struct{}
	once   sync.Once
}

func newZenBody(br *bufio.Reader, conn net.Conn, hdr http.Header, ctx context.Context) *zenBody {
	b := &zenBody{conn: conn, cancel: make(chan struct{})}
	switch strings.ToLower(hdr.Get("Transfer-Encoding")) {
	case "chunked":
		b.src = &zenChunkedReader{br: br}
	default:
		if cl := hdr.Get("Content-Length"); cl != "" {
			if n, err := strconv.ParseInt(cl, 10, 64); err == nil {
				b.src = io.LimitReader(br, n)
			} else {
				b.src = br
			}
		} else {
			b.src = br
		}
	}
	switch strings.ToLower(hdr.Get("Content-Encoding")) {
	case "gzip":
		if zr, err := gzip.NewReader(b.src); err == nil {
			b.src = zr
		}
	case "deflate":
		if zr, err := zlib.NewReader(b.src); err == nil {
			b.src = zr
		}
	case "br", "zstd":
		log.Printf("zen: response uses Content-Encoding %q, which the gateway cannot decode — output may be garbled", hdr.Get("Content-Encoding"))
	}
	go func() {
		select {
		case <-ctx.Done():
			conn.Close()
		case <-b.cancel:
		}
	}()
	return b
}

func (b *zenBody) Read(p []byte) (int, error) { return b.src.Read(p) }

func (b *zenBody) Close() error {
	b.once.Do(func() { close(b.cancel) })
	return b.conn.Close()
}

// zenChunkedReader decodes HTTP/1.1 chunked transfer framing; trailers
// after the terminating chunk are drained and discarded.
type zenChunkedReader struct {
	br        *bufio.Reader
	remaining int64
	eof       bool
}

func (c *zenChunkedReader) Read(p []byte) (int, error) {
	for c.remaining == 0 {
		if c.eof {
			return 0, io.EOF
		}
		line, err := c.br.ReadString('\n')
		if err != nil {
			return 0, err
		}
		sizeField := strings.TrimSpace(line)
		if i := strings.IndexByte(sizeField, ';'); i >= 0 {
			sizeField = sizeField[:i]
		}
		size, err := strconv.ParseInt(sizeField, 16, 64)
		if err != nil || size < 0 {
			return 0, fmt.Errorf("zen: bad chunk size %q", strings.TrimSpace(line))
		}
		if size == 0 {
			c.eof = true
			for { // drain trailers
				t, err := c.br.ReadString('\n')
				if err != nil || t == "\r\n" || t == "\n" {
					break
				}
			}
			return 0, io.EOF
		}
		c.remaining = size
	}
	n := len(p)
	if int64(n) > c.remaining {
		n = int(c.remaining)
	}
	n, err := c.br.Read(p[:n])
	c.remaining -= int64(n)
	if c.remaining == 0 && err == nil {
		if _, cerr := c.br.Discard(2); cerr != nil { // trailing CRLF
			return n, cerr
		}
	}
	return n, err
}
